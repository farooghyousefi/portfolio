const defaultLanguage = "en";
const storageKey = "portfolio-language";
const languageButtons = document.querySelectorAll("[data-lang]");
const translatableElements = document.querySelectorAll("[data-i18n]");
const ariaLabelElements = document.querySelectorAll("[data-i18n-aria-label]");
const titleElements = document.querySelectorAll("[data-i18n-title]");
const metaDescription = document.querySelector('meta[name="description"]');
const backToTopButton = document.querySelector("[data-back-to-top]");

function getNestedTranslation(language, key) {
  return key
    .split(".")
    .reduce((value, part) => value?.[part], translations[language]);
}

function setLanguage(language) {
  const selectedLanguage = translations[language] ? language : defaultLanguage;
  const isRtl = selectedLanguage === "fa";

  document.documentElement.lang = selectedLanguage;
  document.documentElement.dir = isRtl ? "rtl" : "ltr";
  document.title = translations[selectedLanguage].meta.title;

  if (metaDescription) {
    metaDescription.setAttribute(
      "content",
      translations[selectedLanguage].meta.description,
    );
  }

  translatableElements.forEach((element) => {
    const translation = getNestedTranslation(
      selectedLanguage,
      element.dataset.i18n,
    );

    if (translation !== undefined) {
      if (element.dataset.i18nHtml === "true") {
        element.innerHTML = translation;
      } else {
        element.textContent = translation;
      }
    }
  });

  ariaLabelElements.forEach((element) => {
    const translation = getNestedTranslation(
      selectedLanguage,
      element.dataset.i18nAriaLabel,
    );

    if (translation !== undefined) {
      element.setAttribute("aria-label", translation);
    }
  });

  titleElements.forEach((element) => {
    const translation = getNestedTranslation(
      selectedLanguage,
      element.dataset.i18nTitle,
    );

    if (translation !== undefined) {
      element.setAttribute("title", translation);
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === selectedLanguage;

    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  localStorage.setItem(storageKey, selectedLanguage);
}

function updateBackToTopVisibility() {
  if (!backToTopButton) {
    return;
  }

  const shouldShow = window.scrollY > 520;

  backToTopButton.classList.toggle("is-visible", shouldShow);
  backToTopButton.setAttribute("aria-hidden", String(!shouldShow));
  backToTopButton.tabIndex = shouldShow ? 0 : -1;
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.lang);
  });
});

if (backToTopButton) {
  backToTopButton.addEventListener("click", () => {
    const prefersReducedMotion = window.matchMedia(
      "(prefers-reduced-motion: reduce)",
    ).matches;

    window.scrollTo({
      top: 0,
      behavior: prefersReducedMotion ? "auto" : "smooth",
    });
  });

  updateBackToTopVisibility();
  window.addEventListener("scroll", updateBackToTopVisibility, {
    passive: true,
  });
}

setLanguage(localStorage.getItem(storageKey) || defaultLanguage);
